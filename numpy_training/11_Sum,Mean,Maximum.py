import numpy as np

a = np.array([1,2,3,4,5,6])

print(f"Sum of all elements in the array a is {np.sum(a)}")
print(f"Means of all elements in the array a is {np.mean(a)}")
print(f"Max of all elements in the array a is {np.max(a)}")
print(f"Min of all elements in the array a is {np.min(a)}")
print(f"Standard Deviation of all elements in the array a is {np.std(a)}")